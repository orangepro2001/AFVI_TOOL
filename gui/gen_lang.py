#!/usr/bin/env python3
"""Embed the four language packs (the same JSON files the other front ends use) as C strings."""
import json, sys
src, out = sys.argv[1], sys.argv[2]
tags = ["ko", "zh-Hans", "zh-Hant", "en"]
def lit(s):
    return '"' + "".join(c if (32 <= ord(c) < 127 and c not in '"\\?') else "".join("\\%03o" % b for b in c.encode("utf-8")) for c in s) + '"'
with open(out, "w") as f:
    f.write("/* generated by gen_lang.py, do not edit */\nconst char *const LANG_JSON[4] = {\n")
    for t in tags:
        d = json.load(open(f"{src}/{t}.json", encoding="utf-8"))
        f.write("  " + lit(json.dumps(d, ensure_ascii=False)) + ",\n")
    f.write("};\n")
